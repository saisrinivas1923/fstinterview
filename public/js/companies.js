// Helper: Fast filter for letter-by-letter live suggestions
window.getCompanySuggestions = function(query, limit = 12) {
  if (!query || query.trim().length === 0) return [];
  const q = query.trim().toLowerCase();
  
  // First match starts-with, then contains
  const startsWith = [];
  const contains = [];

  for (const comp of window.COMPANY_DATABASE) {
    const lower = comp.toLowerCase();
    if (lower.startsWith(q)) {
      startsWith.push(comp);
    } else if (lower.includes(q)) {
      contains.push(comp);
    }
    if (startsWith.length + contains.length >= limit * 2) break;
  }

  return [...startsWith, ...contains].slice(0, limit);
};
